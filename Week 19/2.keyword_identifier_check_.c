#include <stdio.h>
int main()
{
    char a[1000], b[1000];
    scanf("%[^$]", a);

    int j = 0, f = 0, c = 0;
    for (int i = 0; a[i] != '\0'; i++)
    {
        if (a[i] != ' ' && a[i] != ';' &&
            a[i] != '\n' && a[i] != '(' &&
            a[i] != ')' && a[i] != '{' &&
            a[i] != '}' && a[i] != '<' &&
            a[i] != '>' && a[i] != '+' && a[i] != '=')
        {
            b[j++] = a[i];
        }
        else if (j > 0)
        {

            b[j] = '\0';
            j = 0;
            printf("%s : ", b);

            if (b[0] >= '0' && b[0] <= '9')
                c = 1;

            if ((b[0] == 'i' && b[1] == 'f' && b[2] == '\0') ||
                (b[0] == 'f' && b[1] == 'o' && b[2] == 'r' && b[3] == '\0') ||
                (b[0] == 'i' && b[1] == 'n' && b[2] == 't' && b[3] == '\0') ||
                (b[0] == 'e' && b[1] == 'l' && b[2] == 's' && b[3] == 'e' && b[4] == '\0') ||
                (b[0] == 'c' && b[1] == 'h' && b[2] == 'a' && b[3] == 'r' && b[4] == '\0') ||
                (b[0] == 'w' && b[1] == 'h' && b[2] == 'i' && b[3] == 'l' && b[4] == 'e' && b[5] == '\0') ||
                (b[0] == 'f' && b[1] == 'l' && b[2] == 'o' && b[3] == 'a' && b[4] == 't' && b[5] == '\0') ||
                (b[0] == 'r' && b[1] == 'e' && b[2] == 't' && b[3] == 'u' && b[4] == 'r' && b[5] == 'n' && b[6] == '\0'))
            {
                f = 1;
            }
            
            if (c == 1)
                printf("(Not classified as keyword or identifier)\n");
                
            else if (f == 1)
                printf("Keyword\n");
            else
                printf("Identifier\n");
            f = c = 0;
        }
    }
}
